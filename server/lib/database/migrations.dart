import 'package:postgres/postgres.dart';

/// Append migrations; never edit a migration already applied in production.
const migrations = <List<String>>[
  [
    '''CREATE TABLE users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL, password_hash TEXT NOT NULL, salt TEXT NOT NULL,
      nickname TEXT NOT NULL, created_at TEXT NOT NULL,
      avatar_url TEXT NOT NULL DEFAULT '', intro TEXT NOT NULL DEFAULT '')''',
    'CREATE UNIQUE INDEX users_username_unique ON users (lower(username))',
    '''CREATE TABLE sessions (token_hash TEXT PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at TEXT NOT NULL)''',
    '''CREATE TABLE characters (id TEXT PRIMARY KEY,
      owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      published INTEGER NOT NULL DEFAULT 1 CHECK (published IN (0, 1)),
      bundle TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)''',
    'CREATE INDEX characters_owner ON characters(owner_id)',
    '''CREATE TABLE images (id TEXT PRIMARY KEY,
      owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      mime TEXT NOT NULL, data BYTEA NOT NULL, created_at TEXT NOT NULL)''',
    '''CREATE TABLE user_state (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      key TEXT NOT NULL, value TEXT, updated_at BIGINT NOT NULL, PRIMARY KEY(user_id, key))''',
    '''CREATE TABLE character_friends (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      character_id TEXT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
      created_at TEXT NOT NULL, PRIMARY KEY(user_id, character_id))''',
    'CREATE INDEX character_friends_character ON character_friends(character_id)',
  ],
  [
    // Queryable maintenance views without rewriting serialized player saves.
    '''CREATE VIEW character_overview AS SELECT c.id,c.owner_id,u.username,
      c.bundle::jsonb->'character'->>'name' AS name,c.published,c.created_at,c.updated_at,
      (SELECT count(*) FROM character_friends f WHERE f.character_id=c.id) AS friend_count
      FROM characters c JOIN users u ON u.id=c.owner_id''',
    '''CREATE VIEW user_state_overview AS SELECT s.user_id,u.username,s.key,
      split_part(s.key,'_',1) AS category,s.updated_at,
      octet_length(s.value) AS bytes,s.value IS NULL AS deleted
      FROM user_state s JOIN users u ON u.id=s.user_id''',
  ],
];

Future<void> migrate(Connection connection) => connection.runTx((tx) async {
      // Serialize schema updates when more than one API process starts.
      await tx.execute('SELECT pg_advisory_xact_lock(734105201)');
      await tx.execute('''CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())''');
      final rows = await tx
          .execute('SELECT version FROM schema_migrations ORDER BY version');
      final applied = rows.map((r) => r[0] as int).toSet();
      if (applied.any((v) => v > migrations.length)) {
        throw StateError(
            'Database schema is newer than this server. Do not downgrade it.');
      }
      for (var i = 0; i < migrations.length; i++) {
        if (applied.contains(i + 1)) continue;
        for (final sql in migrations[i]) {
          await tx.execute(sql);
        }
        await tx.execute(r'INSERT INTO schema_migrations(version) VALUES ($1)',
            parameters: [i + 1]);
      }
    });
